#!/usr/bin/env python3
"""Generate src/core/bgapi_tables.c from the Silicon Labs BGAPI headers.

Inputs (unmodified SDK headers, the same ones the TMS Configurator builds with):
  sl_bt_api.h   message ID defines (sl_bt_cmd_*_id / sl_bt_rsp_*_id / sl_bt_evt_*_id)
                and the event structs
  sli_bt_api.h  the command / response structs (wire layout)
  sl_status.h   status code names

The generated C file takes payload sizes from sizeof() of the SDK's own packed
structs, so the compiler (not this script) decides every length. The script
only records which structs exist and whether their last member is a
variable-length array (uint8array: 1-byte length, byte_array: 2-byte length).

Usage: gen_bgapi_tables.py <silabs header dir> <output .c>
"""
import re
import sys
from collections import defaultdict
from pathlib import Path


def struct_bodies(text):
    """Return {struct_name: [member lines]} for every PACKSTRUCT(struct X {...})."""
    out = {}
    for m in re.finditer(r"PACKSTRUCT\(\s*struct\s+(\w+)\s*\{(.*?)\}\s*\);", text, re.S):
        members = []
        body = re.sub(r"/\*.*?\*/", "", m.group(2), flags=re.S)
        body = re.sub(r"//[^\n]*", "", body)
        for line in body.split(";"):
            line = line.strip()
            if line:
                members.append(line)
        out[m.group(1)] = members
    return out


def array_kind(members, struct_name):
    """0 = fixed size, 1 = trailing uint8array, 2 = trailing byte_array."""
    kind = 0
    for i, mem in enumerate(members):
        t = mem.split()[0]
        if t in ("uint8array", "byte_array"):
            if i != len(members) - 1:
                sys.exit(f"{struct_name}: variable array is not the last member; generator needs updating")
            kind = 1 if t == "uint8array" else 2
    return kind


def main():
    hdr_dir = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    api = (hdr_dir / "sl_bt_api.h").read_text(errors="replace")
    sli = (hdr_dir / "sli_bt_api.h").read_text(errors="replace")
    status = (hdr_dir / "sl_status.h").read_text(errors="replace")

    structs = struct_bodies(api)
    structs.update(struct_bodies(sli))

    ids = re.findall(r"#define\s+sl_bt_(cmd|rsp|evt)_(\w+?)_id\s+(0x[0-9a-fA-F]{8})", api)
    seen = set()
    rows = []
    for kind, name, val in ids:
        key = (kind, name)
        if key in seen:
            continue
        seen.add(key)
        v = int(val, 16)
        sname = f"sl_bt_{kind}_{name}_s"
        if sname in structs:
            size_expr = f"sizeof(struct {sname})"
            akind = array_kind(structs[sname], sname)
        else:
            # No struct in the SDK: commands/events without parameters carry an
            # empty payload; a response without outputs carries only 'result'.
            size_expr = "sizeof(struct sl_bt_rsp_error_s)" if kind == "rsp" else "0"
            akind = 0
        rows.append((v, kind, name, size_expr, akind))

    # Sanity: every command has a response and vice versa (same ID value).
    cmds = {(r[0]) for r in rows if r[1] == "cmd"}
    rsps = {(r[0]) for r in rows if r[1] == "rsp"}
    if cmds != rsps:
        sys.exit(f"command/response ID sets differ: {sorted(cmds ^ rsps)}")

    # Class names: the SDK's own doxygen group ("@addtogroup sl_bt_<group> <Title>")
    # that prefixes every message of the class; longest matching group wins.
    groups = set(re.findall(r"@addtogroup\s+sl_bt_(\w+)\s", api))
    by_class = defaultdict(list)
    for v, kind, name, _, _ in rows:
        by_class[(v >> 16) & 0xFF].append(name)
    class_names = {}
    for cls, names in by_class.items():
        cands = [g for g in groups if all(n.startswith(g + "_") for n in names)]
        if not cands:
            sys.exit(f"class 0x{cls:02x}: no SDK group matches {names[:3]}")
        class_names[cls] = max(cands, key=len)

    statuses = []
    for m in re.finditer(r"#define\s+(SL_STATUS_\w+)\s+\(\(sl_status_t\)(0x[0-9a-fA-F]+)\)", status):
        name, val = m.group(1), int(m.group(2), 16)
        if name.endswith("_SPACE") or name.endswith("_MASK"):
            continue
        statuses.append((val, name))
    seen_v = set()
    statuses_u = []
    for v, n in statuses:
        if v not in seen_v:
            seen_v.add(v)
            statuses_u.append((v, n))

    L = []
    L.append("/* GENERATED by tools/gen_bgapi_tables.py from the Silicon Labs SDK headers -- do not edit. */")
    L.append('#include "sl_bt_api.h"')
    L.append('#include "sli_bt_api.h"')
    L.append('#include "bgapi_tables.h"')
    L.append("")
    L.append("const bgapi_msg_def_t bgapi_msg_defs[] = {")
    for v, kind, name, size_expr, akind in rows:
        k = {"cmd": "BGAPI_KIND_CMD", "rsp": "BGAPI_KIND_RSP", "evt": "BGAPI_KIND_EVT"}[kind]
        L.append(f'  {{ 0x{v:08x}u, {k}, "{kind}_{name}", (uint16_t){size_expr}, {akind} }},')
    L.append("};")
    L.append("const unsigned bgapi_msg_def_count = sizeof(bgapi_msg_defs) / sizeof(bgapi_msg_defs[0]);")
    L.append("")
    L.append("const bgapi_class_def_t bgapi_class_defs[] = {")
    for cls in sorted(class_names):
        L.append(f'  {{ 0x{cls:02x}u, "{class_names[cls]}" }},')
    L.append("};")
    L.append("const unsigned bgapi_class_def_count = sizeof(bgapi_class_defs) / sizeof(bgapi_class_defs[0]);")
    L.append("")
    L.append("const bgapi_status_def_t bgapi_status_defs[] = {")
    for v, n in statuses_u:
        L.append(f'  {{ 0x{v:04x}u, "{n}" }},')
    L.append("};")
    L.append("const unsigned bgapi_status_def_count = sizeof(bgapi_status_defs) / sizeof(bgapi_status_defs[0]);")
    out_path.write_text("\n".join(L) + "\n")
    print(f"{len(rows)} messages, {len(class_names)} classes, {len(statuses_u)} status codes -> {out_path}")


if __name__ == "__main__":
    main()
